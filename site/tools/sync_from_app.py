#!/usr/bin/env python3
"""Pull the design source of truth out of the app demo (site/app/netrate-demo.html).

The app is the single source of truth for colour, type, spacing, motion, icons and the
brand mark. Re-run this whenever Mohammad sends a new build of the app:

    python3 -I site/tools/sync_from_app.py

Writes:
  site/assets/fonts/vazirmatn-arabic.woff2, vazirmatn-latin.woff2   (variable 100-900)
  site/src/css/tokens.css      the app's token blocks, verbatim (three themes + scales)
  site/src/partials/sprite.svg the app's line icons the site uses + the brand mark
"""
import base64
import re
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
APP = SITE / "app" / "netrate-demo.html"

# icons we never show on the site (money, flags, "send", circular arrows) — brief, section 1
BANNED_ICONS = {"i-banknote", "i-flag", "i-send", "i-refresh"}


def css_blocks(css, selector_re):
    """Yield (selector, body) for top-level rules whose selector matches."""
    for m in re.finditer(selector_re, css):
        start, depth, i = m.end(), 1, m.end()
        while depth and i < len(css):
            depth += {"{": 1, "}": -1}.get(css[i], 0)
            i += 1
        yield m.group(1).strip(), css[start:i - 1]


def main():
    html = APP.read_text(encoding="utf-8")
    css = re.search(r"<style[^>]*>(.*?)</style>", html, re.S).group(1)

    # --- fonts -------------------------------------------------------------
    faces = re.findall(r"@font-face\s*\{([^}]*)\}", css)
    names = []
    for face in faces:
        data = re.search(r"base64,([A-Za-z0-9+/=]+)", face).group(1)
        rng = re.search(r"unicode-range:([^;]+)", face).group(1)
        name = "vazirmatn-arabic.woff2" if "U+0600" in rng else "vazirmatn-latin.woff2"
        (SITE / "assets" / "fonts" / name).write_bytes(base64.b64decode(data))
        names.append((name, rng.strip()))

    # --- tokens ------------------------------------------------------------
    keep = []
    for sel, body in css_blocks(css, r"(:root[^{]*)\{"):
        if "--" not in body:
            continue
        if "--sp-press" in body or "--font:" in body or "data-theme" in sel:
            keep.append(f"{sel} {{{body}}}\n")
    tokens = ("/* GENERATED by site/tools/sync_from_app.py from site/app/netrate-demo.html.\n"
              "   The app is the source of truth: do not edit by hand, re-run the script. */\n\n" + "\n".join(keep))
    # the site's default theme is dusk (set on <html>), so the dark block must not own bare :root
    tokens = tokens.replace(":root,\n:root[data-theme=\"dark\"]", ":root[data-theme=\"dark\"]")
    (SITE / "src" / "css" / "tokens.css").write_text(tokens, encoding="utf-8")

    # --- icons + brand mark -------------------------------------------------
    sprite_src = re.search(r"<svg[^>]*>\s*<defs>(.*?)</defs>", html, re.S).group(1)
    symbols = re.findall(r'(<symbol id="(i-[\w]+)".*?</symbol>)', sprite_src, re.S)
    kept = [s for s, sid in symbols if sid not in BANNED_ICONS]
    mark = re.search(r'<span class="brand-mark pick-mark"[^>]*>\s*<svg[^>]*>(.*?)</svg>', html, re.S).group(1)
    mark = re.sub(r"\s+", " ", mark).strip()
    # CSS cannot reach inside <use>, so the mark takes its colours from inherited custom properties
    mark = mark.replace('class="sp-sq"', 'class="sp-sq" style="fill:var(--mark-fill)"')
    mark = re.sub(r'class="(sp-n2?)"', r'class="\1" style="stroke:var(--mark-ink)"', mark)
    telegram = ('<symbol id="i-telegram" viewBox="0 0 24 24"><path d="M12 3.2a8.8 8.8 0 1 1 0 17.6 8.8 8.8 0 0 1 0-17.6Z"/>'
                '<path d="m7.2 11.6 9-3.6-1.5 8.4-3.2-2.4-1.7 1.6.3-2.6 3.6-3.2-4.6 2.6Z"/></symbol>')
    sprite = ('<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false"><defs>\n'
              + "\n".join(kept) + "\n" + telegram + "\n"
              + f'<symbol id="brand-mark" viewBox="0 0 48 48">{mark}</symbol>\n</defs></svg>\n')
    (SITE / "src" / "partials").mkdir(parents=True, exist_ok=True)
    (SITE / "src" / "partials" / "sprite.svg").write_text(sprite, encoding="utf-8")

    print("fonts:", ", ".join(f"{n} ({(SITE / 'assets/fonts' / n).stat().st_size // 1024} KB)" for n, _ in names))
    print("token blocks:", len(keep))
    print("icons kept:", len(kept), "of", len(symbols), "(dropped:", ", ".join(sorted(BANNED_ICONS)) + ")")


if __name__ == "__main__":
    main()
